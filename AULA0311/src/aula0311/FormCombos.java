    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
     //alerta de confirmação da exclusão
     //o metodo shiwConfirmDialog retorna um int sendo
     /*
     0 : Sim/Yes
     1 : Não/No
     2 :Cancelar/Cancel
     
     */
    int op =  JOptionPane.showConfirmDialog(this, "Deseja realmente excluir?");// TODO add your handling code here:
     if (op==0)
     {
     //clicou em sim/yes
         //excluir/remover o item
         String curso = cmbCursos.getSelectedItem().toString();
         cmbCursos.removeItem(curso);
         JOptionPane.showMessageDialog(this, "Curso excluido com sucesso!");
     }
    }//GEN-LAST:event_btnExcluirActionPerformed

